/**
 * Classifies a chess opening based on played moves
 * @param moves Array of moves in algebraic notation (e.g., ["e4", "c5", "Nf3"])
 * @returns Object containing ECO code and opening name, or null if no match found
 */
export function classifyOpening(moves: string[]): { eco: string; name: string } | null {
  if (!moves || moves.length === 0) {
    return null;
  }

  // Normalize castling notation (handle both O-O and 0-0)
  const normalizedMoves = moves.map(move => move.replace(/0-0/g, "O-O"));

  // Try matching from longest sequence down to shortest (up to 16 moves)
  const maxDepth = Math.min(16, normalizedMoves.length);

  for (let depth = maxDepth; depth > 0; depth--) {
    const moveSequence = normalizedMoves.slice(0, depth).join(" ");

    for (const [eco, name, tableSequence] of ECO_TABLE) {
      if (tableSequence === moveSequence) {
        return { eco, name };
      }
    }
  }

  // No exact match found
  return null;
}

/**
 * Classifies chess time control based on chess.com's time_control string format
 * @param tcStr Time control string (e.g., "300+5", "600+3", or null/undefined)
 * @returns Time control category: 'bullet', 'blitz', 'rapid', 'classical', or 'daily'
 */
export function classifyTimeControl(tcStr: string | null | undefined): string {
  // Handle null, undefined, or '-' cases
  if (!tcStr || tcStr === "-") {
    return "daily";
  }

  // Parse time control string in format "baseTime+increment"
  const parts = tcStr.split("+");
  if (parts.length < 1) {
    return "daily";
  }

  const baseTimeSeconds = parseInt(parts[0], 10);
  if (isNaN(baseTimeSeconds)) {
    return "daily";
  }

  // Classify based on base time in seconds
  if (baseTimeSeconds < 180) {
    return "bullet";
  } else if (baseTimeSeconds < 600) {
    return "blitz";
  } else if (baseTimeSeconds < 1800) {
    return "rapid";
  } else {
    return "classical";
  }
}
